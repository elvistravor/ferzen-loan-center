-- Ferzen Loan Services PostgreSQL schema foundation.
-- Run in Supabase SQL Editor. This creates a new fls_* schema set and does not import SQLite records.
-- Do not place service-role keys in browser code. Keep database access server-side.

create extension if not exists pgcrypto;

create table if not exists public.fls_staff_profiles (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique references auth.users(id) on delete cascade,
  full_name text not null check (char_length(trim(full_name)) between 2 and 120),
  username text not null unique check (username = lower(username)),
  role text not null check (role in ('owner','staff')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.fls_clients (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null,
  address text not null default '',
  notes text not null default '',
  nin text not null default '',
  date_of_birth date,
  gender text not null default '',
  phone_registered_name text not null default '',
  occupation text not null default '',
  employer text not null default '',
  monthly_income numeric(14,0) not null default 0 check (monthly_income >= 0),
  next_of_kin_name text not null default '',
  next_of_kin_relationship text not null default '',
  next_of_kin_phone text not null default '',
  next_of_kin_address text not null default '',
  passport_photo_path text not null default '',
  id_front_photo_path text not null default '',
  id_back_photo_path text not null default '',
  registered_by uuid references public.fls_staff_profiles(id) on delete set null,
  consent_given boolean not null default false,
  consent_at timestamptz,
  signature_path text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.fls_loans (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.fls_clients(id) on delete restrict,
  principal numeric(14,0) not null check (principal > 0),
  annual_rate numeric(7,3) not null check (annual_rate >= 0 and annual_rate <= 500),
  term_months integer not null check (term_months between 1 and 600),
  interest numeric(14,0) not null check (interest >= 0),
  issue_date date not null,
  purpose text not null default '',
  created_by uuid references public.fls_staff_profiles(id) on delete set null,
  agreement_signature_path text not null default '',
  agreement_consent boolean not null default false,
  agreement_signed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.fls_repayments (
  id bigint generated by default as identity primary key,
  loan_id bigint not null references public.fls_loans(id) on delete restrict,
  amount numeric(14,0) not null check (amount > 0),
  payment_date date not null,
  reference text not null default '',
  created_by uuid references public.fls_staff_profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.fls_client_consents (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.fls_clients(id) on delete restrict,
  consent_text_version text not null,
  consent_given boolean not null check (consent_given),
  signature_path text not null default '',
  recorded_by uuid references public.fls_staff_profiles(id) on delete set null,
  recorded_at timestamptz not null default now()
);

create table if not exists public.fls_audit_logs (
  id bigint generated by default as identity primary key,
  staff_profile_id uuid references public.fls_staff_profiles(id) on delete set null,
  action text not null,
  entity text not null,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists fls_clients_phone_idx on public.fls_clients(phone);
create index if not exists fls_loans_client_idx on public.fls_loans(client_id);
create index if not exists fls_repayments_loan_idx on public.fls_repayments(loan_id);
create index if not exists fls_audit_created_idx on public.fls_audit_logs(created_at desc);

-- Private bucket for KYC images and signatures. Never make this bucket public.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fls-private-documents', 'fls-private-documents', false, 5242880,
        array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = false, file_size_limit = 5242880,
  allowed_mime_types = excluded.allowed_mime_types;

-- Client-side table access is deliberately disabled. The future Netlify API must authorize
-- every request and access the database only from server-side environment variables.
alter table public.fls_staff_profiles enable row level security;
alter table public.fls_clients enable row level security;
alter table public.fls_loans enable row level security;
alter table public.fls_repayments enable row level security;
alter table public.fls_client_consents enable row level security;
alter table public.fls_audit_logs enable row level security;

revoke all on public.fls_staff_profiles from anon, authenticated;
